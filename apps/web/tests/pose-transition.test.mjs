import assert from "node:assert/strict";
import { readFile } from "node:fs/promises";
import { SkinnedMesh, Vector3 } from "three";
import { GLTFLoader } from "three/examples/jsm/loaders/GLTFLoader.js";
import { applyPose, captureBindPose, findPose } from "../lib/garment/poses.ts";
import { TRY_ON_ARM_CONFIG, advancePoseTransition, beginPoseTransition, tryOnPose } from "../lib/garment/poseTransition.ts";

const bytes = await readFile(new URL("../../../outputs/avatars/mhr-neutral.glb", import.meta.url));
const gltf = await new Promise((resolve, reject) => new GLTFLoader().parse(bytes.buffer.slice(bytes.byteOffset, bytes.byteOffset + bytes.byteLength), "", resolve, reject));
let mesh; gltf.scene.traverse(child => { if (child instanceof SkinnedMesh) mesh = child; });
assert.ok(mesh);
const bones = new Map(mesh.skeleton.bones.map(bone => [bone.name, bone]));
const bind = captureBindPose(bones);
const rotations = () => new Map([...bones].map(([name, bone]) => [name, bone.quaternion.clone()]));
const close = (expected, message) => { for (const [name, bone] of bones) assert.ok(bone.quaternion.angleTo(expected.get(name)) < 1e-6, `${message}: ${name}`); };
const rest = rotations();
const worldPosition = name => { gltf.scene.updateMatrixWorld(true); return bones.get(name).getWorldPosition(new Vector3()); };
const initialLeft = worldPosition("l_lowarm"), initialRight = worldPosition("r_lowarm");
assert.deepEqual(TRY_ON_ARM_CONFIG, { adductionDeg: 20, walkSwingDeg: 10 });
assert.deepEqual(tryOnPose("rest").rotations.map(({ joint, degrees }) => [joint, degrees]), [["l_uparm", -20], ["r_uparm", 20]]);
assert.deepEqual(tryOnPose("walk").rotations.slice(-4).map(({ joint, degrees }) => [joint, degrees]), [["l_uparm", -20], ["r_uparm", 20], ["l_uparm", 10], ["r_uparm", -10]]);
const walk = beginPoseTransition(bones, bind, "walk");
close(rest, "creating a transition must not snap");
assert.equal(advancePoseTransition(walk, 0.2), false);
assert.ok(bones.get("l_upleg").quaternion.angleTo(rest.get("l_upleg")) > 0.01, "hip should move at midpoint");
const middle = rotations();
const arms = beginPoseTransition(bones, bind, "both-90");
close(middle, "an interrupted transition must start at the current pose");
assert.equal(advancePoseTransition(arms, 0.399), false);
assert.equal(advancePoseTransition(arms, 0.001), true);
const actualArms = rotations();
applyPose(bones, bind, findPose("both-90"));
close(actualArms, "arms-out endpoint matches the shared pose");
const stand = beginPoseTransition(bones, bind, "rest");
assert.equal(advancePoseTransition(stand, 0.4), true);
const actualStand = rotations();
applyPose(bones, bind, tryOnPose("rest"));
close(actualStand, "stand endpoint matches the adjusted pose");
assert.ok(bones.get("l_uparm").quaternion.angleTo(rest.get("l_uparm")) > 0.25);
assert.ok(worldPosition("l_lowarm").x < initialLeft.x, "left elbow is closer to the body");
assert.ok(worldPosition("r_lowarm").x > initialRight.x, "right elbow is closer to the body");
const standLeftZ = worldPosition("l_lowarm").z, standRightZ = worldPosition("r_lowarm").z;
const walkAgain = beginPoseTransition(bones, bind, "walk");
assert.equal(advancePoseTransition(walkAgain, 0.4), true);
const actualWalk = rotations();
applyPose(bones, bind, tryOnPose("walk"));
close(actualWalk, "walk endpoint matches the adjusted pose");
assert.ok(worldPosition("l_lowarm").z < standLeftZ, "left arm swings backward");
assert.ok(worldPosition("r_lowarm").z > standRightZ, "right arm swings forward");
console.log("Try-on pose transitions, 400 ms endpoints and interruption passed");
