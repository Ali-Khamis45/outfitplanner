import assert from "node:assert/strict";
import { BufferGeometry, Float32BufferAttribute, MeshStandardMaterial } from "three";
import { readFile } from "node:fs/promises";
import { createRequire } from "node:module";
import { GLTFLoader } from "three/examples/jsm/loaders/GLTFLoader.js";
import { MeshoptDecoder } from "three/examples/jsm/libs/meshopt_decoder.module.js";
import { easeAttributeName, formatRegion, isFullyClampedAndTight, parseFitMap, parseSizeOptions, isAvailableSize, regionEstimateNote } from "../lib/garment/fitMap.ts";
import { configureHeatmap } from "../lib/garment/heatmap.ts";
import { compressGlb } from "../asset-compression/compress.mjs";
import { fixtureEase } from "./fixture-ease.mjs";

assert.ok(fixtureEase("tshirt-v5.2", "S", 1.34) <= -20, "S chest displays tight red");
assert.ok(fixtureEase("tshirt-v5.2", "XL", 1.34) >= 40, "XL chest displays loose blue");
for (const garment of ["tshirt-v5.2", "pants-v2"]) for (const size of ["S", "M", "L", "XL"]) {
  for (let y = 0.1; y < 1.5; y += 0.001) assert.ok(Math.abs(fixtureEase(garment, size, y + 0.001) - fixtureEase(garment, size, y)) < 1, "fixture field varies smoothly");
}

const fit = parseFitMap({ version: 1, garment: "tshirt", size: "M", body: "mhr-neutral", regions: { chest: { ease_mm: 62, status: "good" }, length: { delta_mm: -15, status: "tight" } }, recommended: true });
const available = { size: "M", fit, glb: "/shirt.glb", sidecar: "/shirt.json" };
const withheld = { size: "L", status: "withheld" };
assert.deepEqual(parseSizeOptions([withheld, available], "mhr-neutral"), [available, withheld]);
assert.deepEqual(parseSizeOptions([{ ...available, status: "available" }, { size: "M", status: "withheld" }, available], "mhr-neutral"), [{ size: "M", status: "withheld" }], "withheld wins conflicting duplicate entries");
assert.deepEqual(parseSizeOptions([{ size: "XL", status: "withheld" }, { ...available, status: "unknown" }], "mhr-neutral"), [{ size: "XL", status: "withheld" }]);
assert.deepEqual(parseSizeOptions([available], "other-body"), []);
assert.equal(isAvailableSize(withheld), false);
assert.equal(isAvailableSize(available), true);
assert.equal(formatRegion("chest", { ease_mm: 62, status: "tight" }, "tshirt-v5.2"), "Chest: tight, 6.2 cm ease (min 7.6 cm)");
assert.equal(formatRegion("hips", { ease_mm: 40, status: "tight" }, "pants-v2"), "Hips: tight, 4.0 cm ease (min 5.1 cm)");
assert.equal(formatRegion("waist", { ease_mm: -10, status: "tight" }, "pants-v2"), "Waist: tight, -1.0 cm ease (min 0.0 cm)");
assert.equal(formatRegion("length", fit.regions.length, "tshirt-v5.2"), "Length: 1.5 cm short (min -4.0 cm from target)");
assert.throws(() => parseFitMap({ ...fit, regions: { chest: { ease_mm: 3, status: "unknown" } } }));
const estimated = parseFitMap({ ...fit, regions: { chest: { ease_mm: 62, status: "tight", clamped: true }, waist: { ease_mm: 80, status: "good", clamped: false }, length: { delta_mm: -15, status: "good" } } });
assert.equal(regionEstimateNote(estimated.regions.chest), "estimated from size chart");
assert.equal(regionEstimateNote(estimated.regions.waist), null);
assert.equal(regionEstimateNote(estimated.regions.length), null);
assert.throws(() => parseFitMap({ ...fit, regions: { chest: { ease_mm: 62, status: "tight", clamped: "true" } } }));
const clamped = { ease_mm: 20, status: "tight", clamped: true };
const shirt = parseFitMap({ ...fit, garment: "tshirt-v5.2", regions: { chest: clamped, waist: clamped, hips: clamped, length: { delta_mm: 0, status: "good" } } });
assert.equal(isFullyClampedAndTight(shirt), true);
assert.equal(isFullyClampedAndTight({ ...shirt, regions: { ...shirt.regions, hips: { ...clamped, clamped: false } } }), false);
assert.equal(isFullyClampedAndTight({ ...shirt, regions: { chest: clamped, waist: clamped } }), false);
assert.equal(isFullyClampedAndTight({ ...shirt, regions: { ...shirt.regions, waist: { ...clamped, status: "good" } } }), false);
assert.equal(isFullyClampedAndTight({ ...shirt, garment: "pants-v2", regions: { waist: clamped, hips: clamped } }), true);
assert.equal(isFullyClampedAndTight({ ...shirt, garment: "pants-v2", regions: { waist: clamped, hips: { ...clamped, clamped: false } } }), false);
assert.equal(isFullyClampedAndTight({ ...shirt, garment: "pants-v2", regions: { waist: { ...clamped, status: "loose" }, hips: { ...clamped, status: "good" } } }), false);
assert.equal(isFullyClampedAndTight({ ...shirt, garment: "other" }), false);
assert.equal(easeAttributeName(["position", "_ease_mm"]), "_ease_mm");
assert.equal(easeAttributeName(["_EASE_MM"]), "_EASE_MM");
const geometry = new BufferGeometry(), material = new MeshStandardMaterial();
geometry.setAttribute("_ease_mm", new Float32BufferAttribute([-20, 0, 40], 1));
assert.equal(configureHeatmap(material, geometry, true), true);
const shader = { vertexShader: "#include <begin_vertex>", fragmentShader: "#include <color_fragment>" };
material.onBeforeCompile(shader, {});
assert.match(shader.vertexShader, /attribute float _ease_mm/);
assert.match(shader.fragmentShader, /mix\(good, tight/);
assert.match(shader.fragmentShader, /mix\(good, loose/);
assert.equal(configureHeatmap(material, geometry, false), false);
assert.equal(configureHeatmap(material, new BufferGeometry(), true), false);
const require = createRequire(new URL("../asset-compression/compress.mjs", import.meta.url));
const { NodeIO } = require("@gltf-transform/core"), { ALL_EXTENSIONS } = require("@gltf-transform/extensions");
const { MeshoptEncoder, MeshoptDecoder: Decoder } = require("meshoptimizer");
await Promise.all([MeshoptEncoder.ready, Decoder.ready]);
const io = new NodeIO().registerExtensions(ALL_EXTENSIONS).registerDependencies({ "meshopt.encoder": MeshoptEncoder, "meshopt.decoder": Decoder });
const document = await io.readBinary(new Uint8Array(await readFile(new URL("fixtures/corrective.glb", import.meta.url))));
const primitive = document.getRoot().listMeshes()[0].listPrimitives()[0], count = primitive.getAttribute("POSITION").getCount();
primitive.setAttribute("_EASE_MM", document.createAccessor().setType("SCALAR").setArray(Float32Array.from({ length: count }, (_, i) => (i % 3) * 30 - 20)).setBuffer(document.getRoot().listBuffers()[0]));
const packed = await compressGlb(await io.writeBinary(document));
const gltf = await new Promise((resolve, reject) => new GLTFLoader().setMeshoptDecoder(MeshoptDecoder).parse(packed.buffer.slice(packed.byteOffset, packed.byteOffset + packed.byteLength), "", resolve, reject));
let mesh; gltf.scene.traverse(node => { if (node.isSkinnedMesh) mesh = node; });
const attribute = easeAttributeName(Object.keys(mesh.geometry.attributes));
assert.ok(attribute, "compressed GLB retains _EASE_MM");
assert.deepEqual([...new Set(Array.from(mesh.geometry.getAttribute(attribute).array))].sort((a, b) => a - b), [-20, 10, 40]);
assert.ok(mesh.morphTargetDictionary.corr_L_abd90 !== undefined, "morph target survives compression");
console.log("Fit map formatting, case-insensitive ease and shader checks passed");
