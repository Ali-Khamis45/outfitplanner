import assert from "node:assert/strict";
import { BoxGeometry, Mesh, MeshStandardMaterial } from "three";
import { applyMeshInspection } from "../lib/garment/inspection.ts";

const body = new Mesh(new BoxGeometry(), new MeshStandardMaterial());
const shirt = new Mesh(new BoxGeometry(), new MeshStandardMaterial());
const bodyGeometry = body.geometry, shirtGeometry = shirt.geometry;
applyMeshInspection(body, true, true);
applyMeshInspection(shirt, false, true);
assert.equal(body.material.wireframe, true);
assert.equal(shirt.material.wireframe, false);
assert.equal(body.receiveShadow, false);
assert.equal(shirt.receiveShadow, false);
assert.equal(body.material.depthTest, true);
assert.equal(shirt.material.depthTest, true);
applyMeshInspection(body, false, true);
applyMeshInspection(shirt, true, true);
assert.equal(body.material.wireframe, false);
assert.equal(shirt.material.wireframe, true);
applyMeshInspection(body, false, false);
applyMeshInspection(shirt, false, false);
assert.equal(body.receiveShadow, true);
assert.equal(shirt.receiveShadow, true);
assert.equal(body.material.wireframe, false);
assert.equal(shirt.material.wireframe, false);
assert.equal(body.geometry, bodyGeometry);
assert.equal(shirt.geometry, shirtGeometry);
body.geometry.dispose(); shirt.geometry.dispose(); body.material.dispose(); shirt.material.dispose();
console.log("Independent body and garment wireframe modes preserve depth testing and restore shadows.");
